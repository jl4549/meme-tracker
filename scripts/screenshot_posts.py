"""
Take a screenshot of each demo version as it looks on Bluesky, so demo.html can show the real post.

Uses Bluesky's own embed page (embed.bsky.app), which shows just the post (author, text, pictures,
the quoted post) without the app around it. Public posts only, no login.

Run from the IS folder, with the project venv (first time: .venv\\Scripts\\python -m playwright install chromium):
    .venv\\Scripts\\python scripts\\screenshot_posts.py            all 27 versions (skips ones already saved)
    .venv\\Scripts\\python scripts\\screenshot_posts.py --redo     take them all again
    .venv\\Scripts\\python scripts\\screenshot_posts.py 3lfor55ezxc2s   only these rkeys

Saves data/screenshots/<rkey>.png (kept out of git: it shows handles and avatars) and
data/screenshots/status.js with what happened to each post:
  ok          screenshot saved
  (a quoted post inside an ok screenshot can still be hidden, if its own author opted out)
  opted_out   the author asked Bluesky not to show their posts outside the app. We respect that:
              no screenshot is kept, and we do not work around it (e.g. by logging in).
  deleted     the post is gone
"""
import json, os, sys
from playwright.sync_api import sync_playwright

OUT = "data/screenshots"
EMBED = "https://embed.bsky.app/embed/{did}/app.bsky.feed.post/{rkey}"


def main():
    args = sys.argv[1:]
    redo = "--redo" in args
    only = {a for a in args if not a.startswith("--")}
    steps = json.load(open("data/meme_chain.json", encoding="utf-8"))["steps"]
    os.makedirs(OUT, exist_ok=True)
    status_path = f"{OUT}/status.json"
    status = json.load(open(status_path, encoding="utf-8")) if os.path.exists(status_path) else {}

    with sync_playwright() as pw:
        browser = pw.chromium.launch()
        page = browser.new_page(viewport={"width": 560, "height": 900}, device_scale_factor=2, color_scheme="light")
        for s in steps:
            rkey = s["id"].split("/")[-1]
            path = f"{OUT}/{rkey}.png"
            if (only and rkey not in only) or (rkey in status and not redo and not only):
                continue
            page.goto(EMBED.format(did=s["details"]["did"], rkey=rkey), wait_until="networkidle", timeout=60000)
            page.wait_for_timeout(1500)   # let pictures finish loading
            body = page.inner_text("body")
            # a quoted post can show the opt-out notice inside an otherwise normal card,
            # so the post itself only counts as hidden when its own author's handle is missing
            if s["author_handle"] not in body and ("not be displayed on external sites" in body or "Post not found" in body):
                status[rkey] = "opted_out" if "external sites" in body else "deleted"
                if os.path.exists(path):
                    os.remove(path)
                print(f"{status[rkey]:<10}", rkey, "·", s["title"])
                continue
            # the post card is the first element inside the page's root; fall back to the whole page
            card = page.locator("#app > *").first
            try:
                card.screenshot(path=path, timeout=10000)
            except Exception:
                page.screenshot(path=path, full_page=True)
            status[rkey] = "ok"
            print("saved     ", path, "·", s["title"])
        browser.close()

    json.dump(status, open(status_path, "w", encoding="utf-8"), indent=1)
    with open(f"{OUT}/status.js", "w", encoding="utf-8") as f:
        f.write("// generated by scripts/screenshot_posts.py\nwindow.SHOTS = " + json.dumps(status) + ";\n")
    from collections import Counter
    print(dict(Counter(status.values())))


if __name__ == "__main__":
    main()
