"""
Read data/quotes_all.json, compare every post with the original and with its parent,
and write data/chain_data.js for chain_viewer.html.

Run from the IS folder:
    python scripts/build_chain.py

What it measures (simple first versions; embeddings/CLIP come later):
  text_sim_root   how similar the caption is to the original caption (0-1, difflib)
  img_dist_root   how different the image is from the original image (0-1, perceptual hash)
  caption_status  kept / edited / new / none
  image_status    inherited (no new image) / same (re-uploaded original) / new
"""
import difflib, json, os
from PIL import Image

SRC = "data/quotes_all.json"
OUT = "data/chain_data.js"
SAME_IMAGE = 0.16      # hash distance below this = same picture (re-upload, crop, screenshot)


def norm(t):
    return " ".join(t.lower().split())


def text_sim(a, b):
    a, b = norm(a), norm(b)
    if not a or not b:
        return 0.0
    return round(difflib.SequenceMatcher(None, a, b).ratio(), 3)


def dhash(path, size=8):
    img = Image.open(path).convert("L").resize((size + 1, size), Image.LANCZOS)
    px = list(img.getdata())
    bits = []
    for row in range(size):
        for col in range(size):
            bits.append(px[row * (size + 1) + col] > px[row * (size + 1) + col + 1])
    return bits


def hdist(a, b):
    return round(sum(x != y for x, y in zip(a, b)) / len(a), 3)


def main():
    posts = json.load(open(SRC, encoding="utf-8"))
    by_id = {p["id"]: p for p in posts}
    root = posts[0]

    # perceptual hash of each post's first own image
    for p in posts:
        loc = p["images"][0]["local"] if p["images"] else None
        p["_hash"] = dhash(loc) if loc and os.path.exists(loc) else None

    # posts are stored parent-before-child, so one pass works
    for p in posts:
        parent = by_id.get(p["parent_id"])
        # the picture a reader actually sees: own image, or the one it quotes
        if p["_hash"] is not None:
            p["_eff_hash"], p["eff_image"] = p["_hash"], p["images"][0]["local"]
        elif parent:
            p["_eff_hash"], p["eff_image"] = parent["_eff_hash"], parent["eff_image"]
        else:
            p["_eff_hash"], p["eff_image"] = None, None

        p["text_sim_root"] = text_sim(p["text"], root["text"])
        p["text_sim_parent"] = text_sim(p["text"], parent["text"]) if parent else 1.0

        if p is root:
            p["img_dist_root"], p["image_status"], p["caption_status"] = 0.0, "original", "original"
            continue

        if p["_hash"] is None:
            p["image_status"] = "inherited"
        else:
            d_parent = hdist(p["_hash"], parent["_eff_hash"]) if parent["_eff_hash"] else 1.0
            p["image_status"] = "same" if d_parent < SAME_IMAGE else "new"
        p["img_dist_root"] = hdist(p["_eff_hash"], root["_hash"]) if p["_eff_hash"] and root["_hash"] else None

        s = p["text_sim_root"]
        p["caption_status"] = ("none" if not p["text"].strip() else
                               "kept" if s >= 0.9 else
                               "edited" if s >= 0.6 else "new")

    for p in posts:
        p.pop("_hash", None)
        p.pop("_eff_hash", None)

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// generated by scripts/build_chain.py\nwindow.CHAIN = ")
        json.dump(posts, f, ensure_ascii=False)
        f.write(";\n")

    from collections import Counter
    print("image:  ", dict(Counter(p["image_status"] for p in posts)))
    print("caption:", dict(Counter(p["caption_status"] for p in posts)))
    print("caption kept + new image (template use):",
          sum(p["caption_status"] in ("kept", "edited") and p["image_status"] == "new" for p in posts))
    print("saved", OUT)


if __name__ == "__main__":
    main()
